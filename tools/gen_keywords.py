#!/usr/bin/env python3
"""Generate src/kgenerated.rs from the installed sqlparse keyword tables.

The order of the merge is the semantics (COMMON -> ORACLE -> MYSQL -> PLPGSQL
-> HQL -> MSACCESS -> SNOWFLAKE -> BIGQUERY -> BASE): a key seen first wins,
later tables never overwrite it.
"""
import sys
from sqlparse import keywords as K

VAR = {
    'Token.Assignment': 'Assignment',
    'Token.Comment.Single': 'CommentSingle',
    'Token.Comment.Single.Hint': 'CommentSingleHint',
    'Token.Generic.Command': 'GenericCommand',
    'Token.Keyword': 'Keyword',
    'Token.Keyword.CTE': 'KeywordCte',
    'Token.Keyword.DCL': 'KeywordDcl',
    'Token.Keyword.DDL': 'KeywordDdl',
    'Token.Keyword.DML': 'KeywordDml',
    'Token.Keyword.Order': 'KeywordOrder',
    'Token.Keyword.TZCast': 'KeywordTzCast',
    'Token.Literal.Number.Float': 'NumberFloat',
    'Token.Literal.Number.Hexadecimal': 'NumberHex',
    'Token.Literal.Number.Integer': 'NumberInteger',
    'Token.Literal.String.Single': 'StringSingle',
    'Token.Literal.String.Symbol': 'StringSymbol',
    'Token.Name': 'Name',
    'Token.Name.Builtin': 'NameBuiltin',
    'Token.Name.Placeholder': 'NamePlaceholder',
    'Token.Operator': 'Operator',
    'Token.Operator.Comparison': 'OperatorComparison',
    'Token.Punctuation': 'Punctuation',
    'Token.Text.Whitespace': 'Whitespace',
    'Token.Text.Whitespace.Newline': 'Newline',
    'Token.Wildcard': 'Wildcard',
}


def rust_str(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def main(out):
    lines = []
    lines.append('// @generated by tools/gen_keywords.py from sqlparse 0.6.1; do not edit.')
    lines.append('use crate::tokens::Tk;')
    lines.append('')
    lines.append('/// `SQL_REGEX`, in order. First match at the current offset wins.')
    lines.append('pub static SQL_REGEX: &[(&str, Tk)] = &[')
    for rx, tt in K.SQL_REGEX:
        if tt is K.PROCESS_AS_KEYWORD:
            name = 'Tk::KeywordLookup'
        else:
            name = 'Tk::' + VAR[str(tt)]
        lines.append('    (%s, %s),' % (rust_str(rx), name))
    lines.append('];')
    lines.append('')
    merged = {}
    order = []
    tables = [K.KEYWORDS_COMMON, K.KEYWORDS_ORACLE, K.KEYWORDS_MYSQL,
              K.KEYWORDS_PLPGSQL, K.KEYWORDS_HQL, K.KEYWORDS_MSACCESS,
              K.KEYWORDS_SNOWFLAKE, K.KEYWORDS_BIGQUERY, K.KEYWORDS]
    total = 0
    retyped = []
    for tbl in tables:
        total += len(tbl)
        for key, tt in tbl.items():
            if key in merged:
                if merged[key] != tt:
                    retyped.append((key, str(merged[key]), str(tt)))
                continue
            merged[key] = tt
            order.append(key)
    lines.append('/// Merged keyword table: %d declared keys, %d distinct keys.' % (total, len(order)))
    lines.append('pub static KEYWORDS: &[(&str, Tk)] = &[')
    for key in order:
        lines.append('    (%s, Tk::%s),' % (rust_str(key), VAR[str(merged[key])]))
    lines.append('];')
    lines.append('')
    lines.append('/// Declared keys across all nine tables (before shadowing).')
    lines.append('pub const DECLARED_KEYS: usize = %d;' % total)
    with open(out, 'w') as fh:
        fh.write('\n'.join(lines) + '\n')
    sys.stderr.write('declared=%d distinct=%d retyped=%s\n' % (total, len(order), retyped))


if __name__ == '__main__':
    main(sys.argv[1] if len(sys.argv) > 1 else 'src/kgenerated.rs')
